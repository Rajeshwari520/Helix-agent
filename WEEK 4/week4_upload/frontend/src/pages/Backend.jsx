function TicketFlow() {
  const { show, hide } = useTip();
  const W = 1200, H = 210, w = 150, gap = (W - 40 - STEPS.length * w) / (STEPS.length - 1);
  return (
    <svg className="arch" viewBox={`0 0 ${W} ${H}`} role="img" aria-label="Life of a ticket in seven steps" xmlns="http://www.w3.org/2000/svg">
      <rect width={W} height={H} fill={BG} />
      <defs><marker id="fa" viewBox="0 0 10 10" refX="9" refY="5" markerWidth="7" markerHeight="7" orient="auto"><path d="M0,0 L10,5 L0,10 z" fill="#b5a68a" /></marker></defs>
      {STEPS.map((s, i) => {
        const x = 20 + i * (w + gap);
        const tip = (e) => show(e, <TipBody value={`${s.n}. ${s.title}`} label={s.detail} rows={[{ label: "Writes", value: s.writes, color: WHO[s.who] }]} />);
        return (
          <g key={s.n}>
            {i > 0 && <path d={`M${x - gap + 4},${92} L${x - 6},${92}`} stroke="#b5a68a" strokeWidth="1.5" markerEnd="url(#fa)" />}
            <g className="node" transform={`translate(${x},30)`} tabIndex={0} role="img" aria-label={`Step ${s.n}: ${s.title}. ${s.detail}. Writes ${s.writes}`}
              onPointerMove={tip} onPointerLeave={hide} onFocus={tip} onBlur={hide}>
              <rect className="box" width={w} height={124} rx="12" fill={CARD} stroke={CARD_LINE} />
              <circle cx="22" cy="24" r="12" fill={WHO[s.who]} />
              <text x="22" y="28.5" textAnchor="middle" fill="#ffffff" fontSize="12" fontWeight="700" fontFamily={FONT}>{s.n}</text>
              <text x="42" y="29" fill={MUTED} fontSize="11" fontWeight="700" letterSpacing="1" fontFamily={FONT}>{s.who.toUpperCase()}</text>
              <text x="14" y="62" fill={INK} fontSize="15" fontWeight="700" fontFamily={FONT}>{s.title}</text>
              {wrap(s.detail, 22).map((line, j) => <text key={j} x="14" y={84 + j * 16} fill={INK2} fontSize="12" fontFamily={FONT}>{line}</text>)}
            </g>
          </g>
        );
      })}
      <text x="20" y="190" fill={MUTED} fontSize="12" fontFamily={FONT}>Hover a step to see what it writes. Nothing reaches the customer before a person decides (steps 4 and 6).</text>
    </svg>
  );
}

function wrap(text, max) {
  const out = [];
  let line = "";
  for (const w of text.split(" ")) {
    if ((line + " " + w).trim().length > max) { out.push(line.trim()); line = w; } else line += ` ${w}`;
  }
  if (line.trim()) out.push(line.trim());
  return out.slice(0, 3);
}

// Saves an <svg> as a PNG (the diagrams use plain hex colours, so the file looks like the screen).
async function downloadPng(svg, filename) {
  const xml = new XMLSerializer().serializeToString(svg);
  const vb = svg.viewBox.baseVal;
  const scale = 2;
  const img = new Image();
  const url = URL.createObjectURL(new Blob([xml], { type: "image/svg+xml" }));
  await new Promise((ok, fail) => { img.onload = ok; img.onerror = fail; img.src = url; });
  const canvas = document.createElement("canvas");
  canvas.width = vb.width * scale; canvas.height = vb.height * scale;
  const ctx = canvas.getContext("2d");
  ctx.drawImage(img, 0, 0, canvas.width, canvas.height);
  URL.revokeObjectURL(url);
  const a = document.createElement("a");
  a.href = canvas.toDataURL("image/png");
  a.download = filename;
  a.click();
}

