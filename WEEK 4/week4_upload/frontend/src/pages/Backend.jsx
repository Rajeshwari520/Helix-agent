const pos = (n) => ({ x: COLS[n.col].x, y: TOP + n.row * GAP });

function Architecture({ sys, selected, onSelect }) {
  const { show, hide } = useTip();
  const byId = Object.fromEntries(NODES.map((n) => [n.id, n]));
  const linked = selected ? new Set(EDGES.filter(([a, b]) => a === selected || b === selected).flat()) : null;
  const W = 1200, H = TOP + 5 * GAP + 10;
  return (
    <svg className="arch" viewBox={`0 0 ${W} ${H}`} role="img" aria-label="Backend architecture: clients, FastAPI routers, services and data" xmlns="http://www.w3.org/2000/svg">
      <rect width={W} height={H} fill={BG} />
      <defs>
        <marker id="ah" viewBox="0 0 10 10" refX="9" refY="5" markerWidth="7" markerHeight="7" orient="auto-start-reverse"><path d="M0,0 L10,5 L0,10 z" fill="#b5a68a" /></marker>
        <marker id="ahg" viewBox="0 0 10 10" refX="9" refY="5" markerWidth="7" markerHeight="7" orient="auto-start-reverse"><path d="M0,0 L10,5 L0,10 z" fill={GOLD} /></marker>
      </defs>
      {COLS.map((c) => <text key={c.label} x={c.x} y={30} fill={MUTED} fontSize="12" fontWeight="700" letterSpacing="1.5" fontFamily={FONT}>{c.label}</text>)}
      {EDGES.map(([a, b]) => {
        const A = byId[a], B = byId[b], pa = pos(A), pb = pos(B);
        const same = A.col === B.col;
        const far = same && Math.abs(A.row - B.row) > 1; // route around the boxes in between, on the right side
        let d;
        if (far) {
          const xr = pa.x + NW, xo = xr + 24, ya = pa.y + NH / 2 + 10, yb = pb.y + NH / 2 - 10;
          d = `M${xr},${ya} H${xo - 8} Q${xo},${ya} ${xo},${ya + 8} V${yb - 8} Q${xo},${yb} ${xo - 8},${yb} H${xr + 2}`;
        } else if (same) {
          d = `M${pa.x + NW / 2},${pa.y + NH} L${pb.x + NW / 2},${pb.y - 2}`;
        } else {
          const x1 = pa.x + NW, y1 = pa.y + NH / 2, x2 = pb.x - 2, y2 = pb.y + NH / 2;
          d = `M${x1},${y1} C${x1 + 45},${y1} ${x2 - 45},${y2} ${x2},${y2}`;
        }
        const on = selected && (a === selected || b === selected);
        return <path key={`${a}-${b}`} d={d} fill="none" stroke={on ? GOLD : "#cbbfa8"} strokeWidth={on ? 2 : 1.2}
          opacity={selected && !on ? 0.25 : 1} markerEnd={`url(#${on ? "ahg" : "ah"})`} />;
      })}
      {NODES.map((n) => {
        const p = pos(n);
        const sel = selected === n.id;
        const dim = linked && !linked.has(n.id);
        const tip = (e) => show(e, <TipBody value={n.title} label={n.stat && sys ? n.stat(sys) : n.sub} />);
        return (
          <g key={n.id} className={`node${sel ? " sel" : ""}`} transform={`translate(${p.x},${p.y})`} opacity={dim ? 0.35 : 1}
            tabIndex={0} role="button" aria-pressed={sel} aria-label={`${n.title}: ${n.sub}`}
            onClick={() => onSelect(sel ? null : n.id)} onKeyDown={(e) => { if (e.key === "Enter" || e.key === " ") { e.preventDefault(); onSelect(sel ? null : n.id); } }}
            onPointerMove={tip} onPointerLeave={hide} onFocus={tip} onBlur={hide}>
            <rect className="box" width={NW} height={NH} rx="10" fill={sel ? "#f6ecd6" : CARD} stroke={sel ? GOLD : CARD_LINE} strokeWidth={sel ? 2 : 1} />
            <rect x="0" y="12" width="4" height={NH - 24} rx="2" fill={LAYER[n.layer]} />
            <text x="16" y="26" fill={INK} fontSize="15" fontWeight="700" fontFamily={FONT}>{n.title}</text>
            <text x="16" y="46" fill={n.id === "intake" ? MUTED : INK2} fontSize="12" fontFamily={FONT}>{n.sub.length > 34 ? `${n.sub.slice(0, 33)}…` : n.sub}</text>
          </g>
        );
      })}
    </svg>
  );
}

